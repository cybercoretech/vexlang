//! Rust code generation backend for Vexlang.
//!
//! Transpiles Vexlang AST to standard, idiomatic Rust source code.

use crate::ast::{Expr, Op, Pattern, Stmt, Type};

#[derive(Debug, Default, Clone, Copy, PartialEq, Eq)]
pub struct RustBackend;

impl RustBackend {
    pub fn new() -> Self {
        Self
    }

    /// Generate Rust source code from a Vexlang program.
    pub fn emit_rust(&self, statements: &[Stmt]) -> String {
        let mut output = String::new();

        // Header comments and attributes for clean compilation
        output.push_str("// Generated by Vexlang Rust backend\n");
        output.push_str("// Source: Vexlang -> Rust transpilation\n");
        output
            .push_str("#![allow(unused_mut, unused_variables, dead_code, unused_assignments, unused_parens, path_statements)]\n\n");

        let mut items = Vec::new();
        let mut main_body = Vec::new();
        let mut has_explicit_main = false;

        for stmt in statements {
            match stmt {
                Stmt::Function { name, .. } => {
                    if name == "main" {
                        has_explicit_main = true;
                    }
                    items.push(stmt);
                }
                Stmt::Record { .. }
                | Stmt::Enum { .. }
                | Stmt::Trait { .. }
                | Stmt::Impl { .. }
                | Stmt::Module { .. }
                | Stmt::Use { .. }
                | Stmt::Export { .. }
                | Stmt::Newtype { .. }
                | Stmt::Contract { .. } => {
                    items.push(stmt);
                }
                _ => {
                    main_body.push(stmt);
                }
            }
        }

        // Emit top-level items (records, enums, functions)
        for item in &items {
            output.push_str(&self.emit_stmt(item, 0));
            output.push('\n');
        }

        // If there are top-level execution statements and no explicit main function, wrap them in main()
        if !has_explicit_main {
            output.push_str("fn main() -> Result<(), Box<dyn std::error::Error>> {\n");
            for stmt in &main_body {
                output.push_str(&self.emit_stmt(stmt, 1));
                output.push('\n');
            }
            output.push_str("    Ok(())\n");
            output.push_str("}\n");
        } else if !main_body.is_empty() {
            // In case there is an explicit main but also top-level statements
            for stmt in &main_body {
                output.push_str(&self.emit_stmt(stmt, 0));
                output.push('\n');
            }
        }

        output
    }

    fn indent(level: usize) -> String {
        "    ".repeat(level)
    }

    fn emit_stmt(&self, stmt: &Stmt, indent_level: usize) -> String {
        let ind = Self::indent(indent_level);
        match stmt {
            Stmt::Function {
                name,
                params,
                return_type,
                body,
            } => {
                let func_code = self.emit_function(name, params, return_type, body);
                format!("{ind}{func_code}")
            }
            Stmt::Record { name, fields } => {
                let record_code = self.emit_record(name, fields);
                format!("{ind}{record_code}")
            }
            Stmt::Enum { name, variants } => {
                let enum_code = self.emit_enum(name, variants);
                format!("{ind}{enum_code}")
            }
            Stmt::Let { name, ty, value } => {
                format!("{ind}{}", self.emit_let(name, ty, value))
            }
            Stmt::Assign { name, value } => {
                format!("{ind}{}", self.emit_assign(name, value))
            }
            Stmt::AssignIndex {
                name,
                indices,
                value,
            } => {
                format!("{ind}{}", self.emit_assign_index(name, indices, value))
            }
            Stmt::ExprStmt(expr) => {
                format!("{ind}{};", self.emit_expr(expr))
            }
            Stmt::If {
                condition,
                then_branch,
                else_branch,
            } => {
                format!("{ind}{}", self.emit_if(condition, then_branch, else_branch))
            }
            Stmt::While { condition, body } => {
                format!("{ind}{}", self.emit_while(condition, body))
            }
            Stmt::Break => format!("{ind}break;"),
            Stmt::Continue => format!("{ind}continue;"),
            Stmt::Return(expr) => match expr {
                Some(e) => format!("{ind}return {};", self.emit_expr(e)),
                None => format!("{ind}return;"),
            },
            Stmt::Trait { name, methods } => {
                let mut out = format!("{ind}pub trait {name} {{\n");
                for (m_name, m_params, m_ret) in methods {
                    let param_strs: Vec<String> = m_params
                        .iter()
                        .map(|(p_name, p_ty)| format!("{}: {}", p_name, self.emit_type(p_ty)))
                        .collect();
                    out.push_str(&format!("{ind}    fn {m_name}({})", param_strs.join(", ")));
                    if !matches!(m_ret, Type::Unit) {
                        out.push_str(&format!(" -> {}", self.emit_type(m_ret)));
                    }
                    out.push_str(";\n");
                }
                out.push_str(&format!("{ind}}}\n"));
                out
            }
            Stmt::Impl {
                trait_name,
                target,
                methods,
            } => {
                let header = if let Some(tr) = trait_name {
                    format!("{ind}impl {tr} for {target} {{\n")
                } else {
                    format!("{ind}impl {target} {{\n")
                };
                let mut out = header;
                for m in methods {
                    out.push_str(&self.emit_stmt(m, indent_level + 1));
                    out.push('\n');
                }
                out.push_str(&format!("{ind}}}\n"));
                out
            }
            Stmt::Module { name, body } => {
                let mut out = format!("{ind}pub mod {name} {{\n");
                for s in body {
                    out.push_str(&self.emit_stmt(s, indent_level + 1));
                    out.push('\n');
                }
                out.push_str(&format!("{ind}}}\n"));
                out
            }
            Stmt::Use { path } => {
                format!("{ind}pub use {};", path.join("::"))
            }
            Stmt::Export { name } => {
                format!("{ind}pub use {name};")
            }
            Stmt::Newtype { name, underlying } => {
                format!(
                    "{ind}#[derive(Debug, Clone, PartialEq)]\npub struct {name}(pub {});\n",
                    self.emit_type(underlying)
                )
            }
            Stmt::Contract { name, .. } => {
                format!("{ind}// Contract {name}\n")
            }
            Stmt::Invariant(expr) => {
                format!("{ind}assert!({});", self.emit_expr(expr))
            }
            Stmt::Ensure { condition, message } => {
                format!(
                    "{ind}if !({}) {{ return Err({}.into()); }}",
                    self.emit_expr(condition),
                    self.emit_expr(message)
                )
            }
            Stmt::Throw(expr) => {
                format!("{ind}return Err({}.into());", self.emit_expr(expr))
            }
            Stmt::Unsafe(expr) => {
                format!("{ind}unsafe {}", self.emit_expr(expr))
            }
            Stmt::Trusted(stmt) => self.emit_stmt(stmt, indent_level),
            Stmt::Test(stmt) => {
                format!("{ind}#[test]\n{}", self.emit_stmt(stmt, indent_level))
            }
            Stmt::Bench(stmt) => {
                format!("{ind}#[bench]\n{}", self.emit_stmt(stmt, indent_level))
            }
            Stmt::Extern { abi, func } => {
                let abi_str = abi.as_deref().unwrap_or("C");
                format!("{ind}extern \"{abi_str}\" {}", self.emit_stmt(func, 0))
            }
        }
    }

    fn emit_function(
        &self,
        name: &str,
        params: &[(String, Type)],
        return_type: &Type,
        body: &Expr,
    ) -> String {
        let mut output = String::new();

        output.push_str("pub fn ");
        output.push_str(name);
        output.push('(');

        let param_strs: Vec<String> = params
            .iter()
            .map(|(p_name, p_ty)| format!("{}: {}", p_name, self.emit_type(p_ty)))
            .collect();
        output.push_str(&param_strs.join(", "));

        output.push(')');

        if !matches!(return_type, Type::Unit) {
            output.push_str(" -> ");
            output.push_str(&self.emit_type(return_type));
        }

        output.push(' ');
        output.push_str(&self.emit_expr(body));
        output
    }

    fn emit_record(&self, name: &str, fields: &[(String, Type)]) -> String {
        let mut output = String::new();
        output.push_str("#[derive(Debug, Clone, PartialEq)]\n");
        output.push_str("pub struct ");
        output.push_str(name);
        output.push_str(" {\n");

        for (field_name, field_ty) in fields {
            output.push_str("    pub ");
            output.push_str(field_name);
            output.push_str(": ");
            output.push_str(&self.emit_type(field_ty));
            output.push_str(",\n");
        }

        output.push('}');
        output
    }

    fn emit_enum(&self, name: &str, variants: &[crate::ast::EnumVariant]) -> String {
        let mut output = String::new();
        let is_all_unit = variants.iter().all(|v| v.fields.is_empty());
        if is_all_unit {
            output.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq)]\n");
        } else {
            output.push_str("#[derive(Debug, Clone, PartialEq)]\n");
        }
        output.push_str("pub enum ");
        output.push_str(name);
        output.push_str(" {\n");

        for variant in variants {
            output.push_str("    ");
            output.push_str(&variant.name);

            if !variant.fields.is_empty() {
                output.push_str(" { ");
                let field_strs: Vec<String> = variant
                    .fields
                    .iter()
                    .map(|(f_name, f_ty)| format!("{}: {}", f_name, self.emit_type(f_ty)))
                    .collect();
                output.push_str(&field_strs.join(", "));
                output.push_str(" }");
            }

            output.push_str(",\n");
        }

        output.push('}');
        output
    }

    fn emit_let(&self, name: &str, ty: &Type, value: &Expr) -> String {
        let mut output = String::new();
        output.push_str("let mut ");
        output.push_str(name);

        if !matches!(ty, Type::Inferred) {
            output.push_str(": ");
            output.push_str(&self.emit_type(ty));
        }

        output.push_str(" = ");
        output.push_str(&self.emit_expr(value));
        output.push(';');
        output
    }

    fn emit_assign(&self, name: &str, value: &Expr) -> String {
        format!("{} = {};", name, self.emit_expr(value))
    }

    fn emit_assign_index(&self, name: &str, indices: &[Expr], value: &Expr) -> String {
        let mut output = String::new();
        output.push_str(name);

        for idx in indices {
            output.push('[');
            output.push_str(&self.emit_expr(idx));
            output.push_str(" as usize]");
        }

        output.push_str(" = ");
        output.push_str(&self.emit_expr(value));
        output.push(';');
        output
    }

    fn emit_if(
        &self,
        condition: &Expr,
        then_branch: &Expr,
        else_branch: &Option<Box<Expr>>,
    ) -> String {
        let mut output = String::new();
        output.push_str("if ");
        output.push_str(&self.emit_expr(condition));
        output.push(' ');
        output.push_str(&self.emit_expr(then_branch));

        if let Some(else_expr) = else_branch {
            output.push_str(" else ");
            output.push_str(&self.emit_expr(else_expr));
        }

        output
    }

    fn emit_while(&self, condition: &Expr, body: &Expr) -> String {
        format!(
            "while {} {}",
            self.emit_expr(condition),
            self.emit_expr(body)
        )
    }

    fn emit_expr(&self, expr: &Expr) -> String {
        match expr {
            Expr::Int(n) => n.to_string(),
            Expr::String(s) => format!("\"{}\".to_string()", s.escape_default()),
            Expr::Bool(b) => b.to_string(),
            Expr::Var(name) => name.clone(),
            Expr::BinaryOp(left, op, right) => {
                format!(
                    "({} {} {})",
                    self.emit_expr(left),
                    self.emit_op(op),
                    self.emit_expr(right)
                )
            }
            Expr::UnaryOp(op, inner) => {
                format!("({}{})", self.emit_op(op), self.emit_expr(inner))
            }
            Expr::Block(stmts, final_expr) => {
                let mut output = String::new();
                output.push_str("{\n");

                for stmt in stmts {
                    output.push_str(&self.emit_stmt(stmt, 1));
                    output.push('\n');
                }

                if let Some(final_expr) = final_expr {
                    output.push_str("    ");
                    output.push_str(&self.emit_expr(final_expr));
                    output.push('\n');
                }

                output.push('}');
                output
            }
            Expr::If {
                condition,
                then_branch,
                else_branch,
            } => self.emit_if(condition, then_branch, else_branch),
            Expr::Call(name, args) => match name.as_str() {
                "println" => {
                    if args.is_empty() {
                        "println!()".to_string()
                    } else if args.len() == 1 {
                        format!("println!(\"{{}}\", {})", self.emit_expr(&args[0]))
                    } else {
                        let fmt = vec!["{}"; args.len()].join(" ");
                        let arg_strs: Vec<String> =
                            args.iter().map(|a| self.emit_expr(a)).collect();
                        format!("println!(\"{fmt}\", {})", arg_strs.join(", "))
                    }
                }
                "print" => {
                    if args.is_empty() {
                        "print!()".to_string()
                    } else if args.len() == 1 {
                        format!("print!(\"{{}}\", {})", self.emit_expr(&args[0]))
                    } else {
                        let fmt = vec!["{}"; args.len()].join(" ");
                        let arg_strs: Vec<String> =
                            args.iter().map(|a| self.emit_expr(a)).collect();
                        format!("print!(\"{fmt}\", {})", arg_strs.join(", "))
                    }
                }
                "ok" => {
                    if !args.is_empty() {
                        format!("Ok({})", self.emit_expr(&args[0]))
                    } else {
                        "Ok(())".to_string()
                    }
                }
                "err" => {
                    if !args.is_empty() {
                        format!("Err({})", self.emit_expr(&args[0]))
                    } else {
                        "Err(())".to_string()
                    }
                }
                "i32" => {
                    if !args.is_empty() {
                        format!("(({}) as i32)", self.emit_expr(&args[0]))
                    } else {
                        "0i32".to_string()
                    }
                }
                "u64" => {
                    if !args.is_empty() {
                        format!("(({}) as u64)", self.emit_expr(&args[0]))
                    } else {
                        "0u64".to_string()
                    }
                }
                _ => {
                    let arg_strs: Vec<String> = args.iter().map(|a| self.emit_expr(a)).collect();
                    format!("{}({})", name, arg_strs.join(", "))
                }
            },
            Expr::Record(name, fields) => {
                let field_strs: Vec<String> = fields
                    .iter()
                    .map(|(f_name, f_val)| format!("{}: {}", f_name, self.emit_expr(f_val)))
                    .collect();
                format!("{} {{ {} }}", name, field_strs.join(", "))
            }
            Expr::Field(inner, field) => {
                format!("{}.{}.clone()", self.emit_expr(inner), field)
            }
            Expr::Array(elems) => {
                let elem_strs: Vec<String> = elems.iter().map(|e| self.emit_expr(e)).collect();
                format!("vec![{}]", elem_strs.join(", "))
            }
            Expr::Index(array, index) => {
                format!(
                    "{}[({}) as usize].clone()",
                    self.emit_expr(array),
                    self.emit_expr(index)
                )
            }
            Expr::Try(inner) => {
                format!("{}?", self.emit_expr(inner))
            }
            Expr::Match { value, arms } => {
                let mut output = String::new();
                output.push_str("match ");
                output.push_str(&self.emit_expr(value));
                output.push_str(" {\n");

                for (pattern, arm_expr) in arms {
                    output.push_str("    ");
                    output.push_str(&self.emit_pattern(pattern));
                    output.push_str(" => ");
                    output.push_str(&self.emit_expr(arm_expr));
                    output.push_str(",\n");
                }

                output.push('}');
                output
            }
            Expr::EnumVariant {
                enum_name,
                variant,
                fields,
            } => {
                if fields.is_empty() {
                    format!("{}::{}", enum_name, variant)
                } else {
                    let field_strs: Vec<String> = fields
                        .iter()
                        .map(|(f_name, f_val)| format!("{}: {}", f_name, self.emit_expr(f_val)))
                        .collect();
                    format!("{}::{} {{ {} }}", enum_name, variant, field_strs.join(", "))
                }
            }
        }
    }

    fn emit_op(&self, op: &Op) -> String {
        match op {
            Op::And => "&&".to_string(),
            Op::Add => "+".to_string(),
            Op::Sub => "-".to_string(),
            Op::Mul => "*".to_string(),
            Op::Div => "/".to_string(),
            Op::Or => "||".to_string(),
            Op::Eq => "==".to_string(),
            Op::Lt => "<".to_string(),
            Op::Gt => ">".to_string(),
            Op::Not => "!".to_string(),
        }
    }

    fn emit_type(&self, ty: &Type) -> String {
        match ty {
            Type::Inferred => "_".to_string(),
            Type::I32 => "i32".to_string(),
            Type::U64 => "u64".to_string(),
            Type::F64 => "f64".to_string(),
            Type::Bool => "bool".to_string(),
            Type::String => "String".to_string(),
            Type::Unit => "()".to_string(),
            Type::Res => "/* res */ ()".to_string(),
            Type::Custom(name) => name.clone(),
            Type::Array(inner) => format!("Vec<{}>", self.emit_type(inner)),
        }
    }

    fn emit_pattern(&self, pattern: &Pattern) -> String {
        match pattern {
            Pattern::Wildcard => "_".to_string(),
            Pattern::Enum {
                enum_name,
                variant,
                bindings,
            } => {
                let name = if let Some(ename) = enum_name {
                    format!("{ename}::{variant}")
                } else {
                    variant.clone()
                };
                if bindings.is_empty() {
                    name
                } else {
                    format!("{name} {{ {} }}", bindings.join(", "))
                }
            }
            Pattern::Result { ok, binding } => {
                let inner = binding.as_deref().unwrap_or("_");
                if *ok {
                    format!("Ok({inner})")
                } else {
                    format!("Err({inner})")
                }
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn parse_to_ast(source: &str) -> Vec<Stmt> {
        let pairs = crate::parser::parse_vex(source).expect("valid parse");
        crate::builder::build_ast(pairs).expect("valid ast")
    }

    #[test]
    fn transpiles_scalars_and_functions() {
        let source = "fn add(a: i32, b: i32) -> i32 { a + b } let result = add(2, 3);";
        let stmts = parse_to_ast(source);
        let backend = RustBackend::new();
        let rust_code = backend.emit_rust(&stmts);

        assert!(rust_code.contains("pub fn add(a: i32, b: i32) -> i32"));
        assert!(rust_code.contains("fn main() -> Result<(), Box<dyn std::error::Error>>"));
        assert!(rust_code.contains("let mut result = add(2, 3);"));
    }

    #[test]
    fn transpiles_records_and_enums() {
        let source = r#"
record Point { x: i32, y: i32 }
enum Status { Active, Inactive }
let p = Point { x: 10, y: 20 };
"#;
        let stmts = parse_to_ast(source);
        let backend = RustBackend::new();
        let rust_code = backend.emit_rust(&stmts);

        assert!(rust_code.contains("#[derive(Debug, Clone, PartialEq)]\npub struct Point"));
        assert!(rust_code.contains("#[derive(Debug, Clone, Copy, PartialEq, Eq)]\npub enum Status"));
        assert!(rust_code.contains("Point { x: 10, y: 20 }"));
    }

    #[test]
    fn transpiles_arrays_and_indexing() {
        let source = "let items: [i32] = [1, 2, 3]; items[0] = 5; items[0];";
        let stmts = parse_to_ast(source);
        let backend = RustBackend::new();
        let rust_code = backend.emit_rust(&stmts);

        assert!(rust_code.contains("let mut items: Vec<i32> = vec![1, 2, 3];"));
        assert!(rust_code.contains("items[0 as usize] = 5;"));
        assert!(rust_code.contains("items[(0) as usize].clone();"));
    }

    #[test]
    fn transpiles_match_and_results() {
        let source = r#"
enum Message { Quit, Echo { text: string } }
fn check(m: Message) -> i32 {
    match m {
        Message::Quit => 0,
        Message::Echo{text} => 1,
    }
}
let res = ok(42);
"#;
        let stmts = parse_to_ast(source);
        let backend = RustBackend::new();
        let rust_code = backend.emit_rust(&stmts);

        assert!(rust_code.contains("match m {"));
        assert!(rust_code.contains("Message::Quit => 0"));
        assert!(rust_code.contains("Message::Echo { text } => 1"));
        assert!(rust_code.contains("let mut res = Ok(42);"));
    }
}
